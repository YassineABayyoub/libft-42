#include "libft.h"

int	ft_atoi(const char *str)
{
	long	result;
	int		sign;
	int		digit;

	result = 0;
	sign = 1;
	while (*str == ' ' || (*str >= '\t' && *str <= '\r'))
		str++;
	if (*str == '-' || *str == '+')
	{
		if (*str == '-')
			sign = -1;
		str++;
	}
	while (ft_isdigit(*str))
	{
		digit = *str - '0';
		if (sign == -1 && result > (result * 10 + digit))
			return (0);
		if (result > (result * 10 + digit))
			return (-1);
		result = result * 10 + digit;
		str++;
	}
	return ((int)(result * sign));
}